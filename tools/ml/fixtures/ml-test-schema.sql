CREATE TABLE ml_models (
	id BIGINT NOT NULL AUTO_INCREMENT,
	model_name VARCHAR(100) NOT NULL,
	model_version VARCHAR(50) NOT NULL,
	model_type VARCHAR(20) NOT NULL,
	symbol VARCHAR(10) NOT NULL,
	model_path VARCHAR(500) NOT NULL,
	model_format VARCHAR(20) NOT NULL,
	model_size_mb DECIMAL(10, 2),
	checksum VARCHAR(64),
	training_start_date DATETIME NOT NULL,
	training_end_date DATETIME NOT NULL,
	training_duration_minutes INTEGER,
	epochs_trained INTEGER NOT NULL,
	early_stopped BOOL NOT NULL,
	training_data_start_date DATETIME NOT NULL,
	training_data_end_date DATETIME NOT NULL,
	training_samples BIGINT NOT NULL,
	validation_samples BIGINT NOT NULL,
	test_samples BIGINT NOT NULL,
	feature_count INTEGER NOT NULL,
	window_size INTEGER NOT NULL,
	performance_7d_mse DECIMAL(12, 8),
	performance_7d_mae DECIMAL(12, 8),
	performance_7d_direction_accuracy DECIMAL(5, 4),
	performance_14d_mse DECIMAL(12, 8),
	performance_14d_mae DECIMAL(12, 8),
	performance_14d_direction_accuracy DECIMAL(5, 4),
	performance_30d_mse DECIMAL(12, 8),
	performance_30d_mae DECIMAL(12, 8),
	performance_30d_direction_accuracy DECIMAL(5, 4),
	overall_performance_score DECIMAL(5, 4),
	hyperparameters TEXT,
	model_architecture TEXT,
	training_config TEXT,
	status VARCHAR(20) NOT NULL,
	is_active BOOL NOT NULL,
	deployed_at DATETIME,
	deprecated_at DATETIME,
	description TEXT,
	created_by VARCHAR(100),
	tags TEXT,
	created_at DATETIME,
	updated_at DATETIME,
	PRIMARY KEY (id),
	CONSTRAINT uq_model_name_version UNIQUE (model_name, model_version)
);

CREATE TABLE ml_predictions (
	id BIGINT NOT NULL AUTO_INCREMENT,
	symbol VARCHAR(10) NOT NULL,
	prediction_date DATE NOT NULL,
	prediction_timeframe VARCHAR(10) NOT NULL,
	target_date DATE NOT NULL,
	batch_id VARCHAR(50) NOT NULL,
	current_price DECIMAL(12, 4) NOT NULL,
	predicted_price DECIMAL(12, 4) NOT NULL,
	predicted_direction VARCHAR(10) NOT NULL,
	price_change_percent DECIMAL(8, 4),
	confidence_score DECIMAL(5, 4) NOT NULL,
	actual_price DECIMAL(12, 4),
	actual_direction VARCHAR(10),
	actual_change_percent DECIMAL(8, 4),
	is_direction_correct BOOL,
	price_error_percent DECIMAL(8, 4),
	model_version VARCHAR(50) NOT NULL,
	model_type VARCHAR(20) NOT NULL,
	features_used TEXT,
	feature_count BIGINT,
	created_at DATETIME,
	updated_at DATETIME,
	result_updated_at DATETIME,
	PRIMARY KEY (id),
	CONSTRAINT uq_symbol_date_timeframe UNIQUE (symbol, prediction_date, prediction_timeframe)
);

CREATE TABLE daily_prices(id BIGINT AUTO_INCREMENT PRIMARY KEY,symbol VARCHAR(10),date DATE,open_price DOUBLE,high_price DOUBLE,low_price DOUBLE,close_price DOUBLE,volume BIGINT,price_change DOUBLE,price_change_percent DOUBLE);

CREATE TABLE technical_signals(id BIGINT AUTO_INCREMENT PRIMARY KEY,symbol VARCHAR(10),signal_type VARCHAR(100),triggered_at TIMESTAMP,signal_strength DOUBLE,indicator_value DOUBLE);
