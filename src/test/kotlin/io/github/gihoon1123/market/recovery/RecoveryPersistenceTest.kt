package io.github.gihoon1123.market.recovery

import io.github.gihoon1123.market.MarketDataClient
import io.github.gihoon1123.market.analysis.AdvancedPatternService
import io.github.gihoon1123.market.analysis.OutcomeTrackingService
import io.github.gihoon1123.market.analysis.PatternService
import io.mockk.every
import io.mockk.mockk
import io.mockk.verify
import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Assertions.assertTrue
import org.junit.jupiter.api.BeforeEach
import org.junit.jupiter.api.Test
import org.springframework.jdbc.core.JdbcTemplate
import org.springframework.jdbc.datasource.DriverManagerDataSource
import tools.jackson.databind.json.JsonMapper
import java.time.LocalDate
import java.time.ZoneOffset
import java.util.UUID

class RecoveryPersistenceTest {
    @Test
    fun `analysis executes source dependency order once regardless of requested duplicates`() {
        val start = LocalDate.now().minusDays(240)
        repeat(240) { index ->
            val close = if (index == 220) 200.0 else 100.0 + kotlin.math.sin(index / 5.0) * 10
            prices.save("^GSPC", DailyPrice(start.plusDays(index.toLong()), close, close + 1, close - 1, close, 1000), null)
        }
        every { patterns.discover("^GSPC", "1day") } answers {
            assertTrue(jdbc.queryForObject("SELECT COUNT(*) FROM technical_signals", Long::class.java)!! > 0)
            mapOf("discovered_patterns" to 0, "saved_patterns" to 0)
        }
        val result = service.technical(listOf("^GSPC"), listOf("patterns", "signals", "patterns", "signals"), 365).getValue("^GSPC")
        assertEquals(listOf("signals", "patterns"), result.keys.toList())
        verify(exactly = 1) { patterns.discover("^GSPC", "1day") }
        val saved = (result.getValue("signals") as Map<*, *>)["signals_saved"]
        assertEquals((saved as Number).toLong(), jdbc.queryForObject("SELECT COUNT(*) FROM technical_signals", Long::class.java))
    }

    private lateinit var jdbc: JdbcTemplate
    private lateinit var prices: DailyPriceRepository
    private lateinit var service: RecoveryService
    private val market = mockk<MarketDataClient>()
    private val patterns = mockk<PatternService>()

    @BeforeEach
    fun setup() {
        val mysql = System.getenv("RECOVERY_MYSQL_URL")
        jdbc =
            JdbcTemplate(
                DriverManagerDataSource(
                    mysql ?: "jdbc:h2:mem:${UUID.randomUUID()};DB_CLOSE_DELAY=-1",
                    if (mysql == null) "sa" else System.getenv("RECOVERY_MYSQL_USER"),
                    if (mysql == null) "" else System.getenv("RECOVERY_MYSQL_PASSWORD"),
                ),
            )
        if (mysql == null) {
            jdbc.execute(
                "CREATE TABLE daily_prices(id BIGINT GENERATED BY DEFAULT AS IDENTITY,symbol VARCHAR(10),date DATE,open_price DECIMAL(12,4),high_price DECIMAL(12,4),low_price DECIMAL(12,4),close_price DECIMAL(12,4),volume BIGINT,price_change DECIMAL(12,4),price_change_percent DECIMAL(8,4),created_at TIMESTAMP,updated_at TIMESTAMP,UNIQUE(symbol,date))",
            )
            jdbc.execute(
                "CREATE TABLE technical_signals(id BIGINT GENERATED BY DEFAULT AS IDENTITY,symbol VARCHAR(10),signal_type VARCHAR(50),timeframe VARCHAR(10),triggered_at TIMESTAMP,current_price DECIMAL(12,4),indicator_value DECIMAL(12,4),signal_strength DECIMAL(8,4),created_at TIMESTAMP,updated_at TIMESTAMP)",
            )
        } else {
            jdbc.update("DELETE FROM technical_signals")
            jdbc.update("DELETE FROM daily_prices")
        }
        prices = DailyPriceRepository(jdbc)
        service =
            RecoveryService(prices, market, jdbc, patterns, mockk<AdvancedPatternService>(), mockk<OutcomeTrackingService>())
    }

    @Test
    fun `daily price unique constraint preserves previous rows and missing weekdays`() {
        val date = LocalDate.of(2025, 1, 6)
        val price = DailyPrice(date, 100.0, 110.0, 90.0, 105.0, 1000)
        assertTrue(prices.save("^IXIC", price, 100.0))
        assertEquals(false, prices.save("^IXIC", price.copy(close = 999.0), 100.0))
        assertEquals(105.0, prices.prices("^IXIC", date, date).single().close)
        assertEquals(listOf(date.plusDays(1), date.plusDays(2)), prices.missingDates("^IXIC", date.minusDays(2), date.plusDays(2)))
        assertEquals("2025-01-06", prices.range("^IXIC")["end_date"])
    }

    @Test
    fun `recovery decodes complete yearly rows deduplicates timestamp and drops missing OHLCV`() {
        val time =
            LocalDate
                .now()
                .minusDays(1)
                .atStartOfDay()
                .toEpochSecond(ZoneOffset.UTC)
        val chart =
            JsonMapper.builder().build().readTree(
                """{"timestamp":[$time,${time + 1}],"indicators":{"quote":[{"open":[100,null],"high":[110,110],"low":[90,90],"close":[105,105],"volume":[1000,1000]}]}}""",
            )
        every { market.chart("^IXIC", any(), 3) } returns chart
        assertEquals(1, service.download("^IXIC", 2024, 2025).size)
        assertEquals(1, service.historical(listOf("^IXIC"), 1, true)["^IXIC"]!!["saved_count"])
        assertEquals(1, service.historical(listOf("^IXIC"), 1, true)["^IXIC"]!!["duplicate_count"])
    }

    @Test
    fun `historical indicator crossings persist real generated signals with source timeframe`() {
        val start = LocalDate.now().minusDays(240)
        repeat(240) { index ->
            val close = if (index == 220) 200.0 else 100.0 + kotlin.math.sin(index / 5.0) * 10
            prices.save("^GSPC", DailyPrice(start.plusDays(index.toLong()), close, close + 1, close - 1, close, 1000), null)
        }
        val result = service.signals("^GSPC", 365)
        assertTrue((result["signals_saved"] as Int) > 0)
        assertEquals(result["signals_generated"], result["signals_saved"])
        assertEquals(listOf("1day"), jdbc.queryForList("SELECT DISTINCT timeframe FROM technical_signals", String::class.java))
        assertTrue(
            jdbc.queryForObject("SELECT COUNT(*) FROM technical_signals WHERE signal_type='MA200_breakout_up'", Long::class.java)!! > 0,
        )
    }
}
